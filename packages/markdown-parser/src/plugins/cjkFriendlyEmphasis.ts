import type { MarkdownIt } from '../markdown-it-types'
import type { MarkdownToken } from '../types'

// CJK-friendly emphasis / strong, implementing the `markdown-cjk-friendly`
// specification (https://github.com/tats-u/markdown-cjk-friendly).
//
// CommonMark classifies CJK punctuation as Unicode punctuation, so a `**` run
// next to it is neither left- nor right-flanking in the way CJK text needs:
//
//   说明**「A」**。和**「B」**。  ->  说明**「A」<strong>。和</strong>「B」**。   (wrong span)
//   **快。**Pi 的底层            ->  **快。**Pi 的底层                        (stays literal)
//
// Chinese/Japanese/Korean prose has no spaces between words and punctuation, so
// this is the common case rather than an edge case. The specification amends the
// flanking definitions to treat CJK punctuation as text; for input without a CJK
// character next to the run the amended rules are identical to CommonMark, so
// English (and every other non-CJK) document parses exactly as before.
//
// The upstream `markdown-it-cjk-friendly` plugin swaps `md.inline.State`, which
// markdown-it-ts does not read (its inline parser constructs its state class
// directly), so the rule is applied here instead: the `emphasis` inline rule is
// replaced with one that reports the CJK-friendly `can_open`/`can_close` flags to
// the delimiter stack. Pairing (`balance_pairs`) and token rewriting
// (`emphasis.postProcess`) stay untouched.
//
// Only emphasis/strong markers (`*`/`_`) are covered. GFM `~~` keeps the
// CommonMark flanking rules: CJK-aware strikethrough is a separate specification.

// `isCjkRegex` from the specification's generated range table (ranges.md,
// Unicode 18, generated by `node --run print-ranges -- -l js`). Only escape
// casing and two singleton ranges differ from the published literal (eslint
// --fix); the class matches the published one for every code point.
// It deliberately contains the combining marks U+3099/U+309A — `isCjk` below
// tests a single code point, never a multi-code-point sequence.
// eslint-disable-next-line no-misleading-character-class
const CJK_CHAR_RE = /^[\u1100-\u11FF\u20A9\u2329\u232A\u2630-\u2637\u268A-\u268F\u2E80-\u2E99\u2E9B-\u2EF3\u2F00-\u2FD5\u2FF0-\u303E\u3041-\u3096\u3099-\u30FF\u3105-\u312F\u3131-\u318E\u3190-\u31E5\u31EF-\u321E\u3220-\u3247\u3250-\uA48C\uA490-\uA4C6\uA960-\uA97C\uAC00-\uD7A3\uD7B0-\uD7C6\uD7CB-\uD7FB\uF900-\uFAFF\uFE10-\uFE19\uFE30-\uFE52\uFE54-\uFE66\uFE68-\uFE6B\uFF01-\uFFBE\uFFC2-\uFFC7\uFFCA-\uFFCF\uFFD2-\uFFD7\uFFDA-\uFFDC\uFFE0-\uFFE6\uFFE8-\uFFEE\u{16FE0}-\u{16FE4}\u{16FF0}-\u{16FF6}\u{17000}-\u{18CDA}\u{18CFF}-\u{18D20}\u{18D80}-\u{18DF2}\u{18E00}-\u{19191}\u{191A0}-\u{191D2}\u{1AFF0}-\u{1AFF3}\u{1AFF5}-\u{1AFFB}\u{1AFFD}\u{1AFFE}\u{1B000}-\u{1B128}\u{1B132}\u{1B150}-\u{1B152}\u{1B155}\u{1B164}-\u{1B168}\u{1B170}-\u{1B2FB}\u{1D300}-\u{1D356}\u{1D360}-\u{1D376}\u{1F1AE}\u{1F200}\u{1F202}\u{1F210}-\u{1F219}\u{1F21B}-\u{1F22E}\u{1F230}\u{1F231}\u{1F237}\u{1F23B}\u{1F240}-\u{1F248}\u{1F260}-\u{1F265}\u{1F7DA}\u{20000}-\u{3FFFD}]/u

const SPACE = 0x20
const ASTERISK = 0x2A
const UNDERSCORE = 0x5F

// Variation Selectors Supplement (Ideographic Variation Selector).
const IVS_START = 0xE0100
const IVS_END = 0xE01EF
// Variation Selectors Block, excluding the Emoji Presentation Selector U+FE0F.
const NON_EMOJI_VS_START = 0xFE00
const NON_EMOJI_VS_END = 0xFE0E
// The four `StandardizedVariants.txt` "fullwidth form" quotation marks.
const ZS_RE = /^\p{Zs}$/u
const CJK_AMBIGUOUS_QUOTE_RE = /^[\u2018\u2019\u201C\u201D]$/u

interface MarkdownUtils {
  isWhiteSpace: (code: number) => boolean
  isMdAsciiPunct: (code: number) => boolean
  isPunctChar: (char: string) => boolean
}

interface ScannedDelims {
  can_open: boolean
  can_close: boolean
  length: number
}

interface DelimiterLike {
  marker: number
  length: number
  token: number
  end: number
  open: boolean
  close: boolean
}

interface InlineStateLike {
  src: string
  pos: number
  posMax: number
  delimiters: DelimiterLike[]
  tokens: MarkdownToken[]
  md?: { utils?: MarkdownUtils }
  push: (type: string, tag: string, nesting: number) => MarkdownToken
}

function isCjk(code: number) {
  if (code < 0x1100)
    return false
  return CJK_CHAR_RE.test(String.fromCodePoint(code))
}

// Same classification as markdown-it's `isMdAsciiPunct(code) || isPunctChar(
// fromCodePoint(code))`, but the ASCII case never builds a string, matching the
// ASCII fast path the upstream inline scanner uses.
function isPunctCode(utils: MarkdownUtils, code: number) {
  if (utils.isMdAsciiPunct(code))
    return true
  if (code >= 0 && code < 0x80)
    return false
  return utils.isPunctChar(String.fromCodePoint(code))
}

function isPreviousCjk(code: number) {
  return isCjk(code) || (code >= IVS_START && code <= IVS_END)
}

function isTwoPreviousCjk(code: number, previous: number) {
  return isCjk(code) || (previous === 0xFE01 && CJK_AMBIGUOUS_QUOTE_RE.test(String.fromCodePoint(code)))
}

/**
 * Code point before `pos`, plus the index it starts at. The start of the line
 * counts as a space.
 */
function getPreviousCodePoint(src: string, pos: number): [number, number] {
  if (pos <= 0)
    return [SPACE, -1]

  const charCode = src.charCodeAt(pos - 1)
  if ((charCode & 0xFC00) !== 0xDC00)
    return [charCode, pos - 1]

  const codePoint = src.codePointAt(pos - 2)
  return codePoint !== undefined && codePoint > 0xFFFF
    ? [codePoint, pos - 2]
    : [charCode, pos - 1]
}

/**
 * `StateInline#scanDelims` with CJK characters treated as text.
 * Mirrors markdown-it-cjk-friendly's override.
 */
export function scanCjkFriendlyDelims(state: InlineStateLike, start: number, canSplitWord: boolean): ScannedDelims {
  const utils = state.md?.utils
  if (!utils)
    return { can_open: false, can_close: false, length: 0 }

  const { src, posMax } = state
  const marker = src.charCodeAt(start)

  const [lastChar, lastCharPos] = getPreviousCodePoint(src, start)
  let lastMainChar = lastChar
  let twoPrevChar: number | null = null

  // A general-use variation selector applies to the character before it, so the
  // flanking decision looks past the selector. A selector after a space is
  // treated as its own character.
  if (lastChar >= NON_EMOJI_VS_START && lastChar <= NON_EMOJI_VS_END) {
    twoPrevChar = getPreviousCodePoint(src, lastCharPos)[0]
    if (!ZS_RE.test(String.fromCodePoint(twoPrevChar)))
      lastMainChar = twoPrevChar
  }

  let pos = start
  while (pos < posMax && src.charCodeAt(pos) === marker)
    pos++
  const length = pos - start

  // The end of the line counts as a space.
  const nextChar = pos < posMax ? src.codePointAt(pos) ?? SPACE : SPACE

  const isLastWhiteSpace = utils.isWhiteSpace(lastMainChar)
  const isNextWhiteSpace = utils.isWhiteSpace(nextChar)
  if (isLastWhiteSpace || isNextWhiteSpace)
    return { can_open: !isNextWhiteSpace, can_close: !isLastWhiteSpace, length }

  const isLastPunctChar = isPunctCode(utils, lastMainChar)
  const isNextPunctChar = isPunctCode(utils, nextChar)

  // For `_` the flanking flags do not depend on CJK-ness, and these two
  // assignments are exactly CommonMark's `can_open`/`can_close`.
  let leftFlanking = isLastPunctChar
  let rightFlanking = isNextPunctChar

  if (canSplitWord) {
    const isEitherCjkChar = isCjk(nextChar)
      || (twoPrevChar !== null
        ? isTwoPreviousCjk(twoPrevChar, lastChar)
        : isPreviousCjk(lastChar))
    leftFlanking ||= isEitherCjkChar || !isNextPunctChar
    rightFlanking ||= isEitherCjkChar || !isLastPunctChar
  }

  return { can_open: leftFlanking, can_close: rightFlanking, length }
}

/**
 * Drop-in replacement for markdown-it's `emphasis` rule that scans delimiters
 * with `scanCjkFriendlyDelims`. Token shapes, delimiter records and the
 * `state.pos` advance match the upstream rule exactly.
 */
function emphasis(state: unknown, silent?: boolean) {
  if (silent)
    return false

  const s = state as InlineStateLike
  const start = s.pos
  const marker = s.src.charCodeAt(start)
  if (marker !== ASTERISK && marker !== UNDERSCORE)
    return false

  const scanned = scanCjkFriendlyDelims(s, start, marker === ASTERISK)
  if (!scanned || scanned.length === 0)
    return false

  const markerChar = marker === ASTERISK ? '*' : '_'
  const delimiters = s.delimiters
  const tokens = s.tokens
  for (let i = 0; i < scanned.length; i++) {
    const token = s.push('text', '', 0)
    token.content = markerChar
    delimiters.push({
      marker,
      length: scanned.length,
      token: tokens.length - 1,
      end: -1,
      open: scanned.can_open,
      close: scanned.can_close,
    })
  }

  s.pos += scanned.length
  return true
}

export function applyCjkFriendlyEmphasis(md: MarkdownIt) {
  md.inline.ruler.at('emphasis', emphasis)
}
